CREATE TABLE IF NOT EXISTS users (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  role TEXT NOT NULL CHECK (role IN ('customer','business'))
);
CREATE TABLE IF NOT EXISTS sessions (
  token_hash TEXT PRIMARY KEY,
  user_id INTEGER NOT NULL REFERENCES users(id),
  expires_at TIMESTAMPTZ NOT NULL
);
CREATE TABLE IF NOT EXISTS packages (
  id INTEGER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  business_id INTEGER NOT NULL REFERENCES users(id),
  title TEXT NOT NULL,
  description TEXT NOT NULL,
  category TEXT NOT NULL CHECK (category IN ('Fırın','Restoran','Manav','Kafe')),
  address TEXT NOT NULL,
  price NUMERIC(10,2) NOT NULL CHECK (price > 0),
  original_price NUMERIC(10,2) NOT NULL CHECK (original_price >= price),
  quantity INTEGER NOT NULL CHECK (quantity >= 0),
  pickup_start TIMESTAMPTZ NOT NULL,
  pickup_end TIMESTAMPTZ NOT NULL CHECK (pickup_end > pickup_start),
  version INTEGER NOT NULL DEFAULT 1,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  deleted_at TIMESTAMPTZ,
  seed_key TEXT UNIQUE
);
CREATE TABLE IF NOT EXISTS reservations (
  id INTEGER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  package_id INTEGER NOT NULL REFERENCES packages(id),
  customer_id INTEGER NOT NULL REFERENCES users(id),
  request_key TEXT NOT NULL,
  code TEXT NOT NULL UNIQUE,
  status TEXT NOT NULL DEFAULT 'reserved' CHECK (status IN ('reserved','cancelled','collected')),
  price NUMERIC(10,2) NOT NULL CHECK (price > 0),
  title TEXT NOT NULL,
  business_name TEXT NOT NULL,
  address TEXT NOT NULL,
  pickup_start TIMESTAMPTZ NOT NULL,
  pickup_end TIMESTAMPTZ NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  UNIQUE(customer_id,request_key)
);
CREATE INDEX IF NOT EXISTS reservations_customer_idx ON reservations(customer_id);
CREATE INDEX IF NOT EXISTS reservations_package_idx ON reservations(package_id,status);
CREATE INDEX IF NOT EXISTS packages_business_idx ON packages(business_id);
